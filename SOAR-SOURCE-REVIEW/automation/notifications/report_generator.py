# ==========================================================

def calculate_threat_score(statistics):

    critical = statistics.get("CRITICAL", 0)
    high = statistics.get("HIGH", 0)
    medium = statistics.get("MEDIUM", 0)
    low = statistics.get("LOW", 0)

    score = (
        (critical * 100) +
        (high * 40) +
        (medium * 5) +
        (low * 1)
    )

    if score >= 500:
        risk = "CRITICAL"

    elif score >= 300:
        risk = "HIGH"

    elif score >= 100:
        risk = "MEDIUM"

    else:
        risk = "LOW"

    return score, risk

def write_ioc_summary(report, parsed_events):

    iocs = extract_iocs(parsed_events)

    detections = {}
    severity_count = {}

    for event in parsed_events:

        detection = event.get("Classification")

        if detection:
            detections[detection] = detections.get(detection, 0) + 1

        severity = event.get("Severity")

        if severity:
            severity_count[severity] = severity_count.get(severity, 0) + 1

    report.write("## IOC Intelligence Summary\n\n")

    report.write("### Users\n")
    for item in iocs["Users"]:
        report.write(f"- {item}\n")

    report.write("\n### Hosts\n")
    for item in iocs["Hosts"]:
        report.write(f"- {item}\n")

    report.write("\n### Processes\n")
    for item in iocs["Images"]:
        report.write(f"- {item}\n")

    report.write("\n### Parent Processes\n")
    for item in iocs["Parents"]:
        report.write(f"- {item}\n")

    report.write("\n### Commands\n")
    for item in iocs["Commands"]:
        report.write(f"- {item}\n")

    report.write("\n### MITRE ATT&CK Techniques\n")
    for item in iocs["MITRE"]:
        report.write(f"- {item}\n")

    report.write("\n### Detection Types\n")

    for detection, count in sorted(
        detections.items(),
        key=lambda x: x[1],
        reverse=True
    ):
        report.write(f"- {detection}: {count}\n")

    report.write("\n### Severity Distribution\n")

    for severity, count in sorted(
        severity_count.items(),
        key=lambda x: x[1],
        reverse=True
    ):
        report.write(f"- {severity}: {count}\n")

    report.write("\n---\n\n")


def extract_iocs(parsed_events):

    users = set()
    hosts = set()
    images = set()
    parents = set()
    commands = set()
    mitre = set()

    for event in parsed_events:

        if event.get("User"):
            users.add(event["User"])

        if event.get("Host"):
            hosts.add(event["Host"])

        if event.get("Image"):
            images.add(event["Image"])

        if event.get("Parent Image"):
            parents.add(event["Parent Image"])

        if event.get("Command Line"):
            commands.add(event["Command Line"])

        if event.get("MITRE ATT&CK"):
            mitre.add(event["MITRE ATT&CK"])

    return {
        "Users": sorted(users),
        "Hosts": sorted(hosts),
        "Images": sorted(images),
        "Parents": sorted(parents),
        "Commands": sorted(commands),
        "MITRE": sorted(mitre)
    }

# ==========================================================
# REPORT GENERATOR
# ==========================================================
def generate_report(parsed_events, statistics):

    total_events = len(parsed_events)

    with open(REPORT_FILE, "w", encoding="utf-8") as report:

        # Report Header
        write_header(report)

        # Table of Contents
        write_table_of_contents(report)

        # Executive Summary
        write_summary(
            report,
            statistics,
            total_events
        )

        # IOC Intelligence Summary
        write_ioc_summary(
            report,
            parsed_events
        )

        # Incident Timeline
        write_timeline(
            report,
            parsed_events
        )

        # Analyst Recommendations
        write_recommendations(report)

    print()
    print(Fore.GREEN + "[✓] Threat Hunting Report Generated")
print(Fore.WHITE + f"Saved to: {REPORT_FILE.resolve()}")