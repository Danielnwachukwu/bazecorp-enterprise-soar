# ==========================================================
# CREATE REPORT FILE
# ==========================================================

def create_report_file():

    timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")

    report_file = REPORT_DIR / f"Incident_Report_{timestamp}.md"

    return report_file 

REPORT_FILE = create_report_file()


